def clear(p):
    for r in list(p.runs):
        r._element.getparent().remove(r._element)
    pPr = p._p.get_or_add_pPr()
    for el in pPr.findall(qn('w:numPr')):
        pPr.remove(el)


def set_par(p, text, style=None, size=10.5, bold=None, align=None):
    clear(p)
    if style:
        p.style = doc.styles[style]
    run = p.add_run(text)
    run.font.name = '宋体'
    run.font.size = Pt(size)
    run._element.rPr.rFonts.set(qn('w:eastAsia'), '宋体')
    if bold is not None:
        run.bold = bold
    if align is not None:
        p.alignment = align
    return p


def clean_par(p):
    clear(p)
    p.style = doc.styles['Normal']
    return p


def set_cell(cell, text, size=9.5, bold=False):
    cell.text = ''
    par = cell.paragraphs[0]
    run = par.add_run(str(text))
    run.font.name = '宋体'
    run.font.size = Pt(size)
    run.bold = bold
    run._element.rPr.rFonts.set(qn('w:eastAsia'), '宋体')


def make_table(data, size=9.5):
    t = doc.add_table(rows=0, cols=len(data[0]))
    t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, row in enumerate(data):
        cells = t.add_row().cells
        for j, v in enumerate(row):
            set_cell(cells[j], v, size=size, bold=(i == 0))
    return t


class Cursor:
    """在指定元素之后依次插入段落 / 表格。"""

    def __init__(self, el):
        self.el = el

    def par(self, text, style='Normal', size=10.5, bold=None, align=None):
        p = doc.add_paragraph()
        p.style = doc.styles[style]
        run = p.add_run(text)
        run.font.name = '宋体'
        run.font.size = Pt(size)
        run._element.rPr.rFonts.set(qn('w:eastAsia'), '宋体')
        if bold is not None:
            run.bold = bold
        if align is not None:
            p.alignment = align
        self.el.addnext(p._p)
        self.el = p._p
        return p

    def caption(self, text):
        return self.par(text, size=9, bold=True, align=WD_ALIGN_PARAGRAPH.CENTER)

    def table(self, data, size=9.5):
        t = make_table(data, size=size)
        self.el.addnext(t._tbl)
        self.el = t._tbl
        return t


def figure(p, name, width_in):
    clear(p)
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run()
    run.add_picture(os.path.join(FIG, name), width=Inches(width_in))
    return p


