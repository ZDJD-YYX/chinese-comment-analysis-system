def clear(p):
    for r in list(p.runs):
        r._element.getparent().remove(r._element)
    pPr = p._p.get_or_add_pPr()
    for el in pPr.findall(qn('w:numPr')):
        pPr.remove(el)


def set_par(p, text, style='Normal', size=10.5, bold=None, align=None):
    clear(p)
    if style:
        p.style = doc.styles[style]
    run = p.add_run(text)
    run.font.name = '宋体'
    run.font.size = Pt(size)
    run._element.rPr.rFonts.set(qn('w:eastAsia'), '宋体')
    if bold is not None:
        run.bold = bold
    if align is not None:
        p.alignment = align
    return p


class Cursor:
    def __init__(self, el):
        self.el = el

    def par(self, text, size=10.5, bold=None, align=None):
        p = doc.add_paragraph()
        p.style = doc.styles['Normal']
        run = p.add_run(text)
        run.font.name = '宋体'
        run.font.size = Pt(size)
        run._element.rPr.rFonts.set(qn('w:eastAsia'), '宋体')
        if bold is not None:
            run.bold = bold
        if align is not None:
            p.alignment = align
        self.el.addnext(p._p)
        self.el = p._p
        return p

    def heading(self, text):
        p = doc.add_paragraph()
        p.style = doc.styles['Heading 2']
        run = p.add_run(text)
        run.font.name = '宋体'
        run._element.rPr.rFonts.set(qn('w:eastAsia'), '宋体')
        self.el.addnext(p._p)
        self.el = p._p
        return p

    def caption(self, text):
        return self.par(text, size=9, bold=True, align=WD_ALIGN_PARAGRAPH.CENTER)

    def picture(self, name, width_in):
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.add_run().add_picture(os.path.join(FIG, name), width=Inches(width_in))
        self.el.addnext(p._p)
        self.el = p._p
        return p

    def table(self, data, size=8.5):
        t = doc.add_table(rows=0, cols=len(data[0]))
        t.style = 'Table Grid'
        for i, row in enumerate(data):
            cells = t.add_row().cells
            for j, v in enumerate(row):
                cells[j].text = ''
                run = cells[j].paragraphs[0].add_run(str(v))
                run.font.name = '宋体'
                run.font.size = Pt(size)
                run.bold = (i == 0)
                run._element.rPr.rFonts.set(qn('w:eastAsia'), '宋体')
        self.el.addnext(t._tbl)
        self.el = t._tbl
        return t


